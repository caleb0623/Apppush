// Creates backend/.env from .env.example with freshly generated local secrets,
// and writes .local/setup-mysql.sql, which provisions the app's MySQL user and databases.
// Safe to re-run: an existing backend/.env is never overwritten.
import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = join(root, 'backend', '.env');
const examplePath = join(root, 'backend', '.env.example');
const sqlPath = join(root, '.local', 'setup-mysql.sql');
const port = process.argv.find((a) => a.startsWith('--port='))?.split('=')[1] ?? '3306';

const secret = (bytes = 32) => randomBytes(bytes).toString('base64url');

if (existsSync(envPath)) {
  console.log('backend/.env already exists - leaving it unchanged.');
} else {
  const dbPassword = secret(18);
  const env = readFileSync(examplePath, 'utf8')
    .replaceAll('CHANGE_ME_DB_PASSWORD', dbPassword)
    .replaceAll('localhost:3306', `127.0.0.1:${port}`)
    .replace('CHANGE_ME_JWT_SECRET', secret(48))
    .replace('CHANGE_ME_CREDENTIAL_PEPPER', secret(48))
    .replace('CHANGE_ME_SEED_ADMIN_PASSWORD', secret(12));
  writeFileSync(envPath, env);
  console.log(`Created backend/.env (MySQL port ${port}) with generated secrets.`);
}

const env = readFileSync(envPath, 'utf8');
const password = decodeURIComponent(/DATABASE_URL="mysql:\/\/[^:]+:([^@]+)@/.exec(env)?.[1] ?? '');
const sqlPassword = password.replaceAll("'", "''");

mkdirSync(dirname(sqlPath), { recursive: true });
writeFileSync(
  sqlPath,
  `-- Generated by scripts/setup-env.mjs. Contains a local password: do not commit.
CREATE DATABASE IF NOT EXISTS apppush CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS apppush_test CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS 'apppush'@'localhost' IDENTIFIED BY '${sqlPassword}';
CREATE USER IF NOT EXISTS 'apppush'@'127.0.0.1' IDENTIFIED BY '${sqlPassword}';
ALTER USER 'apppush'@'localhost' IDENTIFIED BY '${sqlPassword}';
ALTER USER 'apppush'@'127.0.0.1' IDENTIFIED BY '${sqlPassword}';
GRANT ALL PRIVILEGES ON apppush.* TO 'apppush'@'localhost', 'apppush'@'127.0.0.1';
GRANT ALL PRIVILEGES ON apppush_test.* TO 'apppush'@'localhost', 'apppush'@'127.0.0.1';
FLUSH PRIVILEGES;
`,
);
console.log('Wrote .local/setup-mysql.sql');
